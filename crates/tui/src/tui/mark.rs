//! The Codewhale mark — the founder raster in braille dots (2×4 per cell).
//!
//! The rows are generated, never hand-drawn: `scripts/brand/braille-mark.py`
//! reads the canonical product mark (`brand/codewhalemarkfinal.png`, PRD
//! section 6: the white whale on the navy rounded square) and derives the
//! hero whale's navy darkness down to a dot grid (threshold 0.3, aspect
//! preserved and centred in the rung's box, all-blank edge columns trimmed,
//! the eye carved as one cleared dot). No redraws, no traced SVG: the dots
//! are a proportional derivative of the founder file. Two rungs from the
//! boxes: [`MarkSize::Small`] (box 11×3 → ink 7×3) and [`MarkSize::Tiny`]
//! (box 8×2 → ink 5×2). The ASCII lane has no mark at all:
//! `glyphs::ascii_fallback` flattens braille to `#`, so the wordmark line
//! stands alone there.
//!
//! The launch renderer owns the braille mark as ordinary terminal cells.
//! Graphics probes below are diagnostics only; startup never paints a second
//! image outside the frame.
//!
//! Motion ("surfacing", founder 2026-09-01): over `MARK_SURFACE_MS` the mark
//! reveals from the bottom of its box upward — the whale rises out of the
//! field — while its colour lerps from the field to the accent through
//! [`surface_progress`]'s raised-cosine ease. Then it holds still forever.
//! Reduced motion passes `progress = 1.0`, which is this same drawing at its
//! endpoint, so the still frame cannot drift from the animated one.

use std::sync::OnceLock;

use ratatui::style::Color;

/// Rungs of the mark's scale ladder, each generated at its own box.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MarkSize {
    /// Box 22×6, ink 14×6 — the launch screen's hero mark. Generated from the
    /// same founder raster as the smaller rungs, at a size where the whale
    /// reads as a whale.
    Large,
    /// Box 11×3, ink 7×3 — the launch header's mark.
    Small,
    /// Box 8×2, ink 5×2 — for stages too narrow for the header lines beside
    /// the small rung.
    Tiny,
}

// generated by scripts/brand/braille-mark.py from brand/codewhalemarkfinal.png
// (founder hero whale 504x453px, threshold 0.3, aspect preserved,
// edge columns trimmed, eye carved)

// LARGE: box 22x6 -> ink 14x6
const LARGE_ROWS: [&str; 6] = [
    "  ⣀⣴⣶⣾⣶⣆      ",
    "⢀⣼⣿⠛⠉⠉⠙⠻⠟⠃    ",
    "⢸⣿⡇    ⢀⣀⣤⣤⣤⣤⡀",
    "⢸⣿⣷⣤⣤⣶⣿⣿⣿⡿⠟⠉⣹⠁",
    "⠈⢻⣿⣿⣿⣿⣿⣷⠟ ⢀⡴⠁ ",
    "  ⠈⠉⠽⠿⣿⠥⠤⠒⠉   ",
];

// SMALL: box 11x3 -> ink 7x3
const SMALL_ROWS: [&str; 3] = [
    "⢠⡶⠛⠧⠄  ", //
    "⣿⣄⣠⣤⣶⠶⠆",
    "⠘⠻⣿⣗⠡⠊ ",
];

// TINY: box 8x2 -> ink 5x2
const TINY_ROWS: [&str; 2] = [
    "⢠⡞⠛⢂⣀", //
    "⠘⠿⣿⠍⠉",
];

impl MarkSize {
    /// Cell footprint as `(cols, rows)` — the ink's, not the design box's.
    #[must_use]
    pub const fn cells(self) -> (u16, u16) {
        match self {
            Self::Large => (14, 6),
            Self::Small => (7, 3),
            Self::Tiny => (5, 2),
        }
    }

    /// The braille rows for this rung. Blank cells are spaces so the
    /// renderer leaves the field behind them untouched.
    #[must_use]
    pub const fn rows(self) -> &'static [&'static str] {
        match self {
            Self::Large => &LARGE_ROWS,
            Self::Small => &SMALL_ROWS,
            Self::Tiny => &TINY_ROWS,
        }
    }
}

/// Blend `from` toward `to` (0.0 → `from`, 1.0 → `to`). At 0 the mark is
/// exactly the field colour, so it rises out of the water rather than over it.
#[must_use]
pub fn lerp_color(from: Color, to: Color, amount: f32) -> Color {
    let amount = amount.clamp(0.0, 1.0);
    match (from, to) {
        (Color::Rgb(fr, fg, fb), Color::Rgb(tr, tg, tb)) => Color::Rgb(
            lerp_channel(fr, tr, amount),
            lerp_channel(fg, tg, amount),
            lerp_channel(fb, tb, amount),
        ),
        // Indexed colours have no channels to interpolate; snap at midpoint.
        _ => {
            if amount >= 0.5 {
                to
            } else {
                from
            }
        }
    }
}

fn lerp_channel(from: u8, to: u8, amount: f32) -> u8 {
    let from = f32::from(from);
    let to = f32::from(to);
    (from + (to - from) * amount).round().clamp(0.0, 255.0) as u8
}

/// Raised-cosine rise over `duration_ms`, saturating at 1.0. Wall-clock keyed,
/// so a dropped frame costs smoothness, never correctness.
#[must_use]
pub fn surface_progress(elapsed_ms: u128, duration_ms: u128) -> f32 {
    if duration_ms == 0 || elapsed_ms >= duration_ms {
        return 1.0;
    }
    let t = elapsed_ms as f32 / duration_ms as f32;
    0.5 * (1.0 - (std::f32::consts::PI * t).cos())
}

// ---------------------------------------------------------------------------
// Kitty graphics capability receipt. No launch image is transmitted.
// ---------------------------------------------------------------------------

/// Capability query: a 1×1 RGB image sent with `a=q` is validated but never
/// stored; a supporting terminal answers `ESC _ G i=31;OK ESC \`.
const KITTY_QUERY: &[u8] = b"\x1b_Gi=31,s=1,v=1,a=q,t=d,f=24;AAAA\x1b\\";
/// A terminal that supports the protocol answers within a millisecond.
const KITTY_QUERY_TIMEOUT: std::time::Duration = std::time::Duration::from_millis(120);

static KITTY_GRAPHICS: OnceLock<bool> = OnceLock::new();

/// Environments worth asking. The query is only issued where the terminal is
/// one that could answer, so terminals that will never reply do not pay the
/// timeout at startup. tmux is excluded: image data needs a passthrough
/// wrapper there, which this tier does not do.
fn kitty_candidate_env(env: impl Fn(&str) -> Option<String>) -> bool {
    if env("TMUX").is_some() {
        return false;
    }
    let term = env("TERM").unwrap_or_default().to_ascii_lowercase();
    let program = env("TERM_PROGRAM").unwrap_or_default().to_ascii_lowercase();
    term.contains("kitty")
        || term.contains("ghostty")
        || matches!(
            program.as_str(),
            "kitty" | "wezterm" | "ghostty" | "konsole"
        )
        || env("KITTY_WINDOW_ID").is_some()
        || env("KONSOLE_VERSION").is_some()
}

/// The terminal's answer to the capability query, decided: `OK` means it
/// validated our image; anything else (an error, no reply) does not.
fn kitty_query_accepted(reply: Option<&[u8]>) -> bool {
    reply.is_some_and(|reply| {
        let text = String::from_utf8_lossy(reply);
        text.contains("_G") && text.contains(";OK")
    })
}

/// Ask the terminal once whether it draws kitty graphics, and cache the
/// answer for the process. Call from the TUI entry point in the same window
/// as `codewhale_palette::probe_terminal_background` — raw mode on, event loop not yet
/// reading stdin — since the reply comes back on stdin.
pub fn probe_kitty_graphics() -> bool {
    *KITTY_GRAPHICS.get_or_init(|| {
        kitty_candidate_env(|key| std::env::var(key).ok())
            && kitty_query_accepted(
                codewhale_palette::osc11::query_terminal(KITTY_QUERY, KITTY_QUERY_TIMEOUT)
                    .as_deref(),
            )
    })
}

/// Whether the terminal reported graphics support; false before the probe runs.
#[must_use]
pub fn kitty_graphics_supported() -> bool {
    KITTY_GRAPHICS.get().copied().unwrap_or(false)
}

// ---------------------------------------------------------------------------
// Sixel graphics tier.
//
// For terminals that draw sixel (foot, mlterm, contour, sixel-enabled xterm,
// WezTerm with kitty graphics off) but never answered the kitty query.
// Keep the capability probe for the terminal receipt; launch has no sixel renderer.
// ---------------------------------------------------------------------------

/// Primary device-attributes request. A sixel terminal answers with its
/// capability parameters, e.g. `ESC [ ? 62 ; 4 c` (foot) or
/// `ESC [ ? 63 ; 1 ; 2 ; 4 ; 6 ; 7 ; 15 ; 18 c` (xterm-sixel); parameter 4 is
/// sixel graphics. Read with `query_terminal_csi`: a DA reply ends at its
/// `c` final byte, not at BEL/ST, so the shared OSC-11 reader would swallow
/// following input waiting for a terminator that never comes.
const SIXEL_QUERY: &[u8] = b"\x1b[c";
/// Same budget as the kitty query: answering terminals reply at once.
const SIXEL_QUERY_TIMEOUT: std::time::Duration = std::time::Duration::from_millis(120);
static SIXEL_GRAPHICS: OnceLock<bool> = OnceLock::new();

/// Environments worth asking. Same contract as the kitty gate: only
/// terminals that answer a DA query promptly, never tmux (image data needs
/// a passthrough wrapper there, which this tier does not do). The DA reply
/// itself decides — `xterm-256color` is listed because Terminal.app, iTerm2
/// and xterm.js answer it at once without parameter 4, which is a fast no.
fn sixel_candidate_env(env: impl Fn(&str) -> Option<String>) -> bool {
    if env("TMUX").is_some() {
        return false;
    }
    let term = env("TERM").unwrap_or_default().to_ascii_lowercase();
    let program = env("TERM_PROGRAM").unwrap_or_default().to_ascii_lowercase();
    term.contains("foot")
        || term.contains("mlterm")
        || term.contains("contour")
        || term == "xterm"
        || term.starts_with("xterm-")
        || term == "st"
        || term.starts_with("st-")
        || program.as_str() == "wezterm"
}

/// The terminal's answer to the primary-DA query, decided: parameter `4`
/// (sixel graphics) present means it draws sixel; anything else does not.
fn da_reports_sixel(reply: Option<&[u8]>) -> bool {
    let Some(reply) = reply else {
        return false;
    };
    let text = String::from_utf8_lossy(reply);
    text.split('\x1b').any(|chunk| {
        let body = chunk.strip_prefix("[?").or_else(|| chunk.strip_prefix("["));
        body.is_some_and(|body| {
            body.strip_suffix('c')
                .is_some_and(|params| params.split(';').any(|param| param == "4"))
        })
    })
}

/// Ask the terminal once whether it draws sixel, and cache the answer for
/// the process. Call after [`probe_kitty_graphics`] in the same pre-loop
/// window (raw mode on, event loop not yet reading stdin). A positive kitty
/// result skips this fallback diagnostic probe; neither probe paints an image.
pub fn probe_sixel_graphics() -> bool {
    *SIXEL_GRAPHICS.get_or_init(|| {
        !kitty_graphics_supported()
            && sixel_candidate_env(|key| std::env::var(key).ok())
            && da_reports_sixel(
                codewhale_palette::osc11::query_terminal_csi(SIXEL_QUERY, SIXEL_QUERY_TIMEOUT)
                    .as_deref(),
            )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_rung_matches_its_declared_footprint_in_braille_only() {
        for size in [MarkSize::Large, MarkSize::Small, MarkSize::Tiny] {
            let (cols, rows) = size.cells();
            let art = size.rows();
            assert_eq!(art.len(), usize::from(rows), "{size:?} row count");
            for line in art {
                assert_eq!(
                    line.chars().count(),
                    usize::from(cols),
                    "{size:?} row {line:?} is not {cols} cells"
                );
                for glyph in line.chars() {
                    // U+2800..=U+28FF is the braille block. Checked directly
                    // rather than through the old buffer renderer's bit
                    // decoder, which went with that renderer.
                    assert!(
                        glyph == ' ' || ('\u{2800}'..='\u{28FF}').contains(&glyph),
                        "{size:?} row {line:?} holds a non-braille glyph {glyph:?}"
                    );
                }
            }
            // Generated rows are trimmed: the first and last columns carry ink.
            assert!(art.iter().any(|line| line.starts_with(|c| c != ' ')));
            assert!(art.iter().any(|line| line.ends_with(|c| c != ' ')));
        }
    }

    #[test]
    fn the_mark_has_an_eye() {
        // The script carves the founder whale's eye as one cleared dot
        // inside the body (bit 0x08 of the eye cell). Without the carve the
        // small rung reads `⣟` there and the tiny rung `⠏`.
        assert_eq!(
            SMALL_ROWS[2].chars().nth(3),
            Some('⣗'),
            "small rung lost its carved eye"
        );
        assert_eq!(
            TINY_ROWS[1].chars().nth(3),
            Some('⠍'),
            "tiny rung lost its carved eye"
        );
    }

    #[test]
    fn surface_progress_is_a_monotonic_rise_that_settles_at_one() {
        assert!((surface_progress(0, 640) - 0.0).abs() < 1e-6);
        assert!((surface_progress(320, 640) - 0.5).abs() < 1e-3);
        assert!((surface_progress(640, 640) - 1.0).abs() < 1e-6);
        assert!((surface_progress(5_000, 640) - 1.0).abs() < 1e-6);
        let mut previous = -1.0;
        for ms in (0..=640).step_by(20) {
            let value = surface_progress(ms, 640);
            assert!(value >= previous, "regressed at {ms}ms");
            previous = value;
        }
    }

    #[test]
    fn a_zero_length_rise_is_settled_not_divided_by_zero() {
        assert!((surface_progress(0, 0) - 1.0).abs() < 1e-6);
    }

    #[test]
    fn kitty_candidates_are_the_terminals_that_can_answer_and_never_tmux() {
        let env = |vars: &[(&str, &str)]| {
            let vars: Vec<(String, String)> = vars
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect();
            move |key: &str| vars.iter().find(|(k, _)| k == key).map(|(_, v)| v.clone())
        };
        assert!(kitty_candidate_env(env(&[("TERM", "xterm-kitty")])));
        assert!(kitty_candidate_env(env(&[("TERM_PROGRAM", "WezTerm")])));
        assert!(kitty_candidate_env(env(&[("TERM", "xterm-ghostty")])));
        assert!(kitty_candidate_env(env(&[("KONSOLE_VERSION", "230800")])));
        assert!(!kitty_candidate_env(env(&[
            ("TERM", "xterm-256color"),
            ("TERM_PROGRAM", "Apple_Terminal")
        ])));
        assert!(!kitty_candidate_env(env(&[
            ("TERM", "xterm-kitty"),
            ("TMUX", "/tmp/tmux-501/default,1,0")
        ])));
    }

    #[test]
    fn the_query_is_accepted_only_on_an_ok_reply() {
        assert!(kitty_query_accepted(Some(b"\x1b_Gi=31;OK")));
        assert!(!kitty_query_accepted(Some(b"\x1b_Gi=31;EINVAL:bad")));
        assert!(!kitty_query_accepted(Some(b"\x1b[?1;2c")));
        assert!(!kitty_query_accepted(None));
    }

    #[test]
    fn sixel_candidates_are_the_terminals_that_answer_da_and_never_tmux() {
        let env = |vars: &[(&str, &str)]| {
            let vars: Vec<(String, String)> = vars
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect();
            move |key: &str| vars.iter().find(|(k, _)| k == key).map(|(_, v)| v.clone())
        };
        assert!(sixel_candidate_env(env(&[("TERM", "foot")])));
        assert!(sixel_candidate_env(env(&[("TERM", "foot-extra")])));
        assert!(sixel_candidate_env(env(&[("TERM", "mlterm")])));
        assert!(sixel_candidate_env(env(&[("TERM", "contour")])));
        // `xterm-256color` is a candidate even though most of its owners
        // decline: Terminal.app, iTerm2 and xterm.js answer DA at once
        // without parameter 4, which is a fast no rather than a timeout.
        assert!(sixel_candidate_env(env(&[("TERM", "xterm-256color")])));
        assert!(sixel_candidate_env(env(&[("TERM", "st-256color")])));
        assert!(sixel_candidate_env(env(&[("TERM_PROGRAM", "WezTerm")])));
        assert!(!sixel_candidate_env(env(&[])));
        assert!(!sixel_candidate_env(env(&[("TERM", "dumb")])));
        assert!(!sixel_candidate_env(env(&[
            ("TERM", "foot"),
            ("TMUX", "/tmp/tmux-501/default,1,0")
        ])));
    }

    #[test]
    fn the_da_reply_decides_on_parameter_four_only() {
        // foot: sixel present.
        assert!(da_reports_sixel(Some(b"\x1b[?62;4c")));
        // xterm-sixel: sixel among other capabilities.
        assert!(da_reports_sixel(Some(b"\x1b[?63;1;2;4;6;7;15;18c")));
        // Plain xterm: answers, no sixel.
        assert!(!da_reports_sixel(Some(b"\x1b[?62;1;2;6;7c")));
        // A 4 inside another parameter is not sixel.
        assert!(!da_reports_sixel(Some(b"\x1b[?62;44c")));
        // A kitty reply is not a DA reply.
        assert!(!da_reports_sixel(Some(b"\x1b_Gi=31;OK\x1b\\")));
        assert!(!da_reports_sixel(None));
    }
}
